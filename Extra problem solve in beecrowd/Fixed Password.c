#include <stdio.h>

int main() {

    int i, n, password=2002;

    for(i=1; i<=1; )
    {
        scanf("%d", &n);

        if(n != password)
        {
            printf("Senha Invalida\n");
        }
        else
        {
            printf("Acesso Permitido\n");
            break;
        }
    }
    i++;

    return 0;
}
