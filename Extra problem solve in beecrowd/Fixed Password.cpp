#include<bits/stdc++.h>
using namespace std;
int main()
{
    int i, n, password=2002;

    for(i=1; i<=1; )
    {
        cin>>n;

        if(n != password)
        {
            cout<<"Senha Invalida"<<endl;
        }
        else
        {
            cout<<"Acesso Permitido"<<endl;
            break;
        }
    }
    i++;

    return 0;
}
