#include<bits/stdc++.h>
using namespace std;
int main()
{
    int a, b, c;
    cin >> a >> b >> c;
    cout << "A = " << a << ", B = " << b << ", C = " << c << endl;
    cout << "A =       " << a << ", B =         " << b << ", C =        " << c << endl;
    cout << "A = 000000" << a << ", B = 00000000" << b << ", C = 0000000" << c << endl;
    cout << "A = " << a << "      , B = " << b << "        , C = " << c << endl;
    return 0;
}